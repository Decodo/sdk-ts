import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { JSONSchema4 } from 'json-schema';
import { compile } from 'json-schema-to-typescript';
import {
  compileOpts,
  fetchIntermediateRepresentation,
  localIrPath,
  outDir,
  toPascalCase,
} from '../web-scraping-api/shared.js';
import type { DataApiEndpointIR, DataApiIR } from './types.js';

const compileType = async (
  schema: JSONSchema4,
  typeName: string,
): Promise<string> => {
  const block = await compile(schema, typeName, compileOpts);
  return block.trimEnd();
};

const getEndpointTypeBlocks = async (
  endpointKey: string,
  endpoint: DataApiEndpointIR,
): Promise<string[]> => {
  const baseName = toPascalCase(endpointKey);
  const blocks: string[] = [];

  if (endpoint.requestSchema) {
    blocks.push(await compileType(endpoint.requestSchema, `${baseName}Request`));
  }
  if (endpoint.queryParameters) {
    blocks.push(await compileType(endpoint.queryParameters, `${baseName}Query`));
  }
  blocks.push(await compileType(endpoint.responseSchema, `${baseName}Response`));

  return blocks;
};

const getDataApiFileContents = async (api: DataApiIR): Promise<string> => {
  const lines: string[] = [];

  lines.push(
    '// Auto-generated by src/codegen/data-api/generate-data-api.ts — do not edit',
  );
  lines.push('');

  for (const [endpointKey, endpoint] of Object.entries(api.endpoints)) {
    for (const block of await getEndpointTypeBlocks(endpointKey, endpoint)) {
      lines.push(block);
      lines.push('');
    }
  }

  lines.push('export const dataApiEndpoints = {');
  for (const [endpointKey, endpoint] of Object.entries(api.endpoints)) {
    lines.push(
      `  ${endpointKey}: { method: ${JSON.stringify(endpoint.method)}, path: ${JSON.stringify(endpoint.path)} },`,
    );
  }
  lines.push('} as const;');
  lines.push('');
  lines.push('export type DataApiEndpoint = keyof typeof dataApiEndpoints;');
  lines.push('');

  return lines.join('\n');
};

export const generateDataApiFile = async (): Promise<void> => {
  const ir = await fetchIntermediateRepresentation();
  const api = ir.apis.dataApi;
  const fileContents = await getDataApiFileContents(api);

  mkdirSync(outDir, { recursive: true });
  const outPath = resolve(outDir, 'data-api.ts');
  writeFileSync(outPath, fileContents);

  console.log(`Generated data API types from ${localIrPath}:`);
  console.log(`  ${outPath} (${Object.keys(api.endpoints).length} endpoints)`);
};
