import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { IrFlowSections, RemoteIr } from '../../schema/types.js';
import { fetchIntermediateRepresentation, outDir } from '../web-scraping-api/shared.js';

const flowSectionsOf = (ir: RemoteIr): IrFlowSections => ({
  operations: ir.operations ?? {},
  flows: ir.flows ?? {},
  surfaces: ir.surfaces ?? {},
  ...(ir.keyCheck && { keyCheck: ir.keyCheck }),
});

export const generateFlowsFile = async (): Promise<void> => {
  const ir = (await fetchIntermediateRepresentation()) as unknown as RemoteIr;
  const sections = flowSectionsOf(ir);
  const fileContents = [
    '// Auto-generated by src/codegen/flows/generate-flows.ts — do not edit',
    '',
    "import type { IrFlowSections } from '../schema/types.js';",
    '',
    `export const flowSectionsVersion = ${JSON.stringify(ir.version)};`,
    '',
    `export const flowSections: IrFlowSections = ${JSON.stringify(sections, null, 2)};`,
    '',
  ].join('\n');

  mkdirSync(outDir, { recursive: true });
  const outPath = resolve(outDir, 'flows.ts');
  writeFileSync(outPath, fileContents);

  console.log(`Generated flows from IR ${ir.version}:`);
  console.log(
    `  ${outPath} (${Object.keys(sections.flows).length} flows, ${Object.keys(sections.surfaces).length} surfaces)`,
  );
};
